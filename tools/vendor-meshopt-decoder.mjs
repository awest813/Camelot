#!/usr/bin/env node
/**
 * Writes public/vendor/meshopt_decoder.js: meshoptimizer's glTF decoder as
 * a classic script that defines `self.MeshoptDecoder`, which is how Babylon
 * loads it (MeshoptCompression.Configuration.decoder.url).  Babylon's
 * default URL is its CDN; the game serves its own copy.
 *
 * Run after updating meshoptimizer:  node tools/vendor-meshopt-decoder.mjs
 * (a unit test fails if the committed copy and the installed package drift).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export function buildDecoderScript(moduleSource, version) {
  const body = moduleSource.replace(/^export \{ MeshoptDecoder \};\s*$/m, "");
  if (body === moduleSource) throw new Error("meshopt_decoder.mjs no longer ends with `export { MeshoptDecoder }`");
  return `// meshoptimizer ${version} glTF decoder (MIT, (C) Arseny Kapoulkine), as a classic\n`
    + `// script for Babylon's MeshoptCompression. Generated by tools/vendor-meshopt-decoder.mjs.\n`
    + body.trimEnd() + "\n\nself.MeshoptDecoder = MeshoptDecoder;\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = new URL("..", import.meta.url);
  const pkg = JSON.parse(readFileSync(new URL("node_modules/meshoptimizer/package.json", root), "utf8"));
  const src = readFileSync(new URL("node_modules/meshoptimizer/meshopt_decoder.mjs", root), "utf8");
  writeFileSync(new URL("public/vendor/meshopt_decoder.js", root), buildDecoderScript(src, pkg.version));
  console.log(`wrote public/vendor/meshopt_decoder.js (meshoptimizer ${pkg.version})`);
}
